/**
 * The service worker that lets the game open and play with no connection. It is generated at build time (see
 * vite.config.ts) so it knows exactly which files make up this build.
 *
 * How it behaves:
 *  - On install it downloads every file of the game once, into a cache named for this build.
 *  - Files are then served from that cache first, so the game starts instantly, online or not.
 *  - The page itself (index.html) is fetched from the network first, so a new version arrives as soon as you are
 *    online and reload; if the network is down or slow (more than 3 seconds), the saved copy is used.
 *  - A new build gets a new cache; the old ones are deleted when the new worker takes over.
 */

/** The files to keep for offline play: the app shell and everything it loads, never the social-share image. */
export function precacheList(files: readonly string[]): string[] {
  const skip = new Set(['og-image.jpg', 'sw.js']);
  const urls = files.filter((f) => !skip.has(f)).map((f) => `/${f}`);
  return ['/', ...urls].sort();
}

/** A short stable name for a set of `name:size` entries, so a changed build gets a fresh cache. */
export function cacheVersion(entries: readonly string[]): string {
  let h = 5381;
  for (const ch of [...entries].sort().join('|')) h = ((h * 33) ^ ch.charCodeAt(0)) >>> 0;
  return h.toString(36);
}

/** The source of the service worker for these files (relative paths, no leading slash) and cache version. */
export function serviceWorkerSource(files: readonly string[], version: string): string {
  return `// Generated by the build; do not edit.
const CACHE = 'toc-${version}';
const FILES = ${JSON.stringify(precacheList(files), null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('toc-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

const NETWORK_WAIT_MS = 3000;
// Module scripts are requested with an Origin header the saved copy was not, and some servers answer with 'Vary: Origin'.
// Without this, such a request would not find its saved copy and the game would not start offline.
const MATCH = { ignoreVary: true };

// The page: network first (so updates arrive), the saved copy when offline or slow.
function page(request) {
  const saved = () => caches.match('/', MATCH).then((hit) => hit || caches.match('/index.html', MATCH));
  const network = fetch(request).then((response) => {
    if (response.ok) {
      const copy = response.clone();
      caches.open(CACHE).then((cache) => cache.put('/', copy));
    }
    return response;
  });
  const timeout = new Promise((resolve) => setTimeout(resolve, NETWORK_WAIT_MS, null));
  return Promise.race([network.catch(() => null), timeout]).then((response) => response || saved().then((hit) => hit || network));
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(page(request));
    return;
  }
  // Everything else is part of this build: saved copy first, the network as a fallback.
  event.respondWith(caches.match(request, MATCH).then((hit) => hit || fetch(request)));
});
`;
}
